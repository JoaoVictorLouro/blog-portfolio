import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_LOCALE, LOCALES } from './i18n/locales.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const localesDir = join(root, 'content/themes/neon-protocol/locales');
const partialsDir = join(root, 'content/themes/neon-protocol/partials');

const NON_DEFAULT_LOCALES = LOCALES.filter((locale) => locale.code !== DEFAULT_LOCALE);
const DEFAULT_LOCALE_META = LOCALES.find((locale) => locale.code === DEFAULT_LOCALE);

function escapeHandlebars(value) {
  return String(value)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\{\{/g, '\\{\\{')
    .replace(/\}\}/g, '\\}\\}');
}

function loadLocaleMessages(code) {
  const path = join(localesDir, `${code}.json`);
  return JSON.parse(readFileSync(path, 'utf8'));
}

function buildPostHasInner(valueForLocale) {
  const branches = NON_DEFAULT_LOCALES.map((locale, index) => {
    const value = valueForLocale(locale);
    const opener = index === 0 ? '#has' : 'else has';
    return `{{${opener} tag="${locale.tagName}"}}${value}`;
  });
  const defaultValue = valueForLocale(DEFAULT_LOCALE_META);
  return `${branches.join('')}{{else}}${defaultValue}{{/has}}`;
}

function buildBlockBranch(valueForLocale) {
  const branches = LOCALES.map((locale, index) => {
    const value = valueForLocale(locale);
    const opener = index === 0 ? '#match' : 'else match';
    return `{{${opener} (block "np_lang") "${locale.code}"}}${value}`;
  });
  const defaultValue = valueForLocale(DEFAULT_LOCALE_META);
  return `${branches.join('')}{{else}}${defaultValue}{{/match}}`;
}

function buildLangBranch(key, messagesByLocale) {
  const valueForLocale = (locale) => escapeHandlebars(messagesByLocale[locale.code][key] ?? key);
  return buildBlockBranch(valueForLocale);
}

function buildNavLinksPartial(messagesByLocale) {
  const navKeys = ['HOME', 'ARTICLES', 'PORTFOLIO', 'ABOUT'];
  const routes = ['/', '/articles/', '/portfolio/', '/about/'];
  const valueForLocale = (locale) => {
    const labels = navKeys
      .map((key, index) => {
        const label = escapeHandlebars(messagesByLocale[locale.code][key] ?? key);
        return `    <li><a class="{{link_class for="/${locale.code}${routes[index]}" activeClass="is-active"}}" href="{{@site.url}}/${locale.code}${routes[index]}">${label}</a></li>`;
      })
      .join('\n');
    return `\n${labels}\n`;
  };
  return {
    post: buildPostHasInner(valueForLocale),
    site: buildBlockBranch(valueForLocale),
  };
}

function buildLocalePrefixPartial() {
  return {
    post: buildPostHasInner((locale) => locale.code),
    site: buildBlockBranch((locale) => locale.code),
  };
}

function buildNavMobilePartial(messagesByLocale) {
  const navKeys = ['HOME', 'ARTICLES', 'PORTFOLIO', 'ABOUT'];
  const routes = ['/', '/articles/', '/portfolio/', '/about/'];
  const icons = ['home_max', 'explore', 'photo_library', 'account_tree'];
  const valueForLocale = (locale) => {
    const links = navKeys
      .map((key, index) => {
        const label = escapeHandlebars(messagesByLocale[locale.code][key] ?? key);
        return `    <a class="{{link_class for="/${locale.code}${routes[index]}" activeClass="is-active"}}" href="{{@site.url}}/${locale.code}${routes[index]}"><span class="material-symbols-outlined" aria-hidden="true">${icons[index]}</span><span>${label}</span></a>`;
      })
      .join('\n');
    return `\n${links}\n`;
  };
  return {
    post: buildPostHasInner(valueForLocale),
    site: buildBlockBranch(valueForLocale),
  };
}

function buildPostLabelPartial(messagesByLocale) {
  const keys = [
    'AUTHOR',
    'UPLOADED',
    'READ_IN_ANOTHER_LANGUAGE',
    'AVAILABLE_IN',
    'NO_TRANSLATIONS',
    'LLM_ATTRIBUTION',
  ];
  const blocks = keys.map((key) => {
    const branch = buildPostHasInner((locale) =>
      escapeHandlebars(messagesByLocale[locale.code][key] ?? key),
    );
    return `{{#match key "${escapeHandlebars(key)}"}}\n  ${branch}\n{{/match}}`;
  });
  return `{{!-- AUTO-GENERATED by scripts/build-theme-i18n.mjs — do not edit --}}\n${blocks.join('\n')}\n`;
}

function buildNpTPartial(messagesByLocale) {
  const keys = Object.keys(messagesByLocale[DEFAULT_LOCALE]).sort();
  const blocks = keys.map((key) => {
    const valueForLocale = (locale) => escapeHandlebars(messagesByLocale[locale.code][key] ?? key);
    const blockBranch = buildBlockBranch(valueForLocale);
    const tagBranch = buildPostHasInner(valueForLocale);
    return `{{#match key "${escapeHandlebars(key)}"}}
  {{#is "post"}}
    {{#post}}
      ${tagBranch}
    {{/post}}
  {{else}}
    ${blockBranch}
  {{/is}}
{{/match}}`;
  });
  return `{{!-- AUTO-GENERATED by scripts/build-theme-i18n.mjs — do not edit --}}\n${blocks.join('\n')}\n`;
}

function buildNavLabelsPartial() {
  const items = LOCALES.map((locale) => {
    return `    <option value="${locale.code}" data-np-locale-label="${escapeHandlebars(locale.nativeLabel)}">${escapeHandlebars(locale.nativeLabel)}</option>`;
  });
  return `{{!-- AUTO-GENERATED by scripts/build-theme-i18n.mjs — do not edit --}}\n${items.join('\n')}\n`;
}

function syncLegacyEnJson(messagesByLocale) {
  const enUs = messagesByLocale[DEFAULT_LOCALE];
  const hasLegacy = readdirSync(localesDir).some((name) => name === 'en.json');
  if (!hasLegacy) {
    return;
  }
  const legacy = {};
  for (const [key, value] of Object.entries(enUs)) {
    if (key.startsWith('HOME') || key.startsWith('ARTICLES') || key.startsWith('PORTFOLIO')) {
      continue;
    }
    legacy[key] = value;
  }
  writeFileSync(join(localesDir, 'en.json'), `${JSON.stringify(legacy, null, 2)}\n`);
}

const messagesByLocale = Object.fromEntries(
  LOCALES.map((locale) => [locale.code, loadLocaleMessages(locale.code)]),
);

const navLinks = buildNavLinksPartial(messagesByLocale);
const localePrefix = buildLocalePrefixPartial();
const navMobile = buildNavMobilePartial(messagesByLocale);

writeFileSync(join(partialsDir, 'np-t.hbs'), buildNpTPartial(messagesByLocale));
writeFileSync(join(partialsDir, 'np-post-label.hbs'), buildPostLabelPartial(messagesByLocale));
writeFileSync(join(partialsDir, 'np-locale-options.hbs'), buildNavLabelsPartial());
writeFileSync(
  join(partialsDir, 'np-locale-prefix-post.hbs'),
  `{{!-- AUTO-GENERATED by scripts/build-theme-i18n.mjs — do not edit --}}\n${localePrefix.post}\n`,
);
writeFileSync(
  join(partialsDir, 'np-locale-prefix-site.hbs'),
  `{{!-- AUTO-GENERATED by scripts/build-theme-i18n.mjs — do not edit --}}\n${localePrefix.site}\n`,
);
writeFileSync(
  join(partialsDir, 'np-nav-links-post.hbs'),
  `{{!-- AUTO-GENERATED by scripts/build-theme-i18n.mjs — do not edit --}}\n<ul class="np-nav-links">\n${navLinks.post}\n</ul>\n`,
);
writeFileSync(
  join(partialsDir, 'np-nav-links-site.hbs'),
  `{{!-- AUTO-GENERATED by scripts/build-theme-i18n.mjs — do not edit --}}\n<ul class="np-nav-links">\n${navLinks.site}\n</ul>\n`,
);
writeFileSync(
  join(partialsDir, 'nav-mobile-post.hbs'),
  `{{!-- AUTO-GENERATED by scripts/build-theme-i18n.mjs — do not edit --}}\n<nav class="np-dock" aria-label="${escapeHandlebars(messagesByLocale[DEFAULT_LOCALE].Menu ?? 'Menu')}">\n${navMobile.post}\n</nav>\n`,
);
writeFileSync(
  join(partialsDir, 'nav-mobile-site.hbs'),
  `{{!-- AUTO-GENERATED by scripts/build-theme-i18n.mjs — do not edit --}}\n<nav class="np-dock" aria-label="${escapeHandlebars(messagesByLocale[DEFAULT_LOCALE].Menu ?? 'Menu')}">\n${navMobile.site}\n</nav>\n`,
);
syncLegacyEnJson(messagesByLocale);

console.log(
  'Generated np-t.hbs, np-post-label.hbs, np-locale-options.hbs, np-locale-prefix-{post,site}.hbs, np-nav-links-{post,site}.hbs, nav-mobile-{post,site}.hbs',
);
