#!/usr/bin/env -S deno run -A

import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LOCALES } from './i18n/locales.mjs';
import { fileRevision, themeAssetPath } from './theme-asset-hash.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const dataDir = join(root, 'content/themes/neon-protocol/assets/data');
const localesDir = join(root, 'content/themes/neon-protocol/locales');
const partialsDir = join(root, 'content/themes/neon-protocol/partials');

const PWA_KEYS = ['PWA_NAME', 'PWA_SHORT_NAME', 'PWA_DESCRIPTION'];

const PWA_ICONS = [
  { file: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
  { file: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
  { file: 'icon-512-maskable.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
];

const iconRevisions = Object.fromEntries(
  await Promise.all(
    PWA_ICONS.map(async ({ file }) => [
      file,
      await fileRevision(themeAssetPath(root, `images/${file}`)),
    ]),
  ),
);

const SHARED = {
  display: 'standalone',
  orientation: 'any',
  background_color: '#121315',
  theme_color: '#121315',
  icons: PWA_ICONS.map((icon) => ({
    src: `../images/${icon.file}?v=${iconRevisions[icon.file]}`,
    sizes: icon.sizes,
    type: icon.type,
    purpose: icon.purpose,
  })),
};

function requiredString(messages, key, localeCode) {
  const value = messages[key];
  if (typeof value !== 'string' || value.trim() === '') {
    throw new Error(`Missing ${key} in locales/${localeCode}.json`);
  }
  return value;
}

await Deno.mkdir(dataDir, { recursive: true });

for (const locale of LOCALES) {
  const messages = JSON.parse(await Deno.readTextFile(join(localesDir, `${locale.code}.json`)));
  for (const key of PWA_KEYS) {
    requiredString(messages, key, locale.code);
  }
  const manifest = {
    id: `/${locale.code}/`,
    name: messages.PWA_NAME,
    short_name: messages.PWA_SHORT_NAME,
    description: messages.PWA_DESCRIPTION,
    start_url: `/${locale.code}/`,
    scope: `/${locale.code}/`,
    lang: locale.bcp47,
    ...SHARED,
  };
  const path = join(dataDir, `manifest-${locale.code}.json`);
  await Deno.writeTextFile(path, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`Wrote manifest-${locale.code}.json`);
}

const browserconfig = `<?xml version="1.0" encoding="utf-8"?>
<browserconfig>
  <msapplication>
    <tile>
      <square150x150logo src="/assets/images/icon-192.png?v=${iconRevisions['icon-192.png']}"/>
      <TileColor>#121315</TileColor>
    </tile>
  </msapplication>
</browserconfig>
`;
await Deno.writeTextFile(join(dataDir, 'browserconfig.xml'), browserconfig);
console.log('Wrote browserconfig.xml');

const NON_DEFAULT_LOCALES = LOCALES.filter((locale) => locale.code !== 'en-us');

function buildPostManifestBranch() {
  const parts = NON_DEFAULT_LOCALES.map((locale, index) => {
    const opener = index === 0 ? '{{#has' : '{{else has';
    return `${opener} tag="${locale.tagName}"}}{{asset "data/manifest-${locale.code}.json"}}`;
  });
  return `${parts.join('')}{{else}}{{asset "data/manifest-en-us.json"}}{{/has}}`;
}

function buildSiteManifestBranch() {
  const parts = LOCALES.map((locale, index) => {
    const opener = index === 0 ? '{{#match' : '{{else match';
    return `${opener} (block "np_lang") "${locale.code}"}}{{asset "data/manifest-${locale.code}.json"}}`;
  });
  return `${parts.join('')}{{else}}{{asset "data/manifest-en-us.json"}}{{/match}}`;
}

const pwaManifestPartial = `{{!-- AUTO-GENERATED by scripts/build-pwa-manifests.mjs — do not edit --}}
{{#is "post"}}
${buildPostManifestBranch()}
{{else}}
${buildSiteManifestBranch()}
{{/is}}
`;

await Deno.writeTextFile(join(partialsDir, 'np-pwa-manifest.hbs'), pwaManifestPartial);
console.log('Wrote partials/np-pwa-manifest.hbs');
